-- Catálogo de comunas de Chile y relación universidad → comuna.
--
-- `universidad.comuna` era texto libre. Se reemplaza por una FK a un catálogo
-- para que la comuna se SELECCIONE (el texto libre producía variantes que no
-- coincidían al agrupar en los informes). La migración no pierde datos: cada
-- universidad existente se enlaza a su comuna comparando el texto normalizado
-- (minúsculas, sin tildes ni signos), y si alguna fila no encuentra comuna la
-- migración entera se aborta ANTES de borrar la columna de texto.
--
-- Fuente del catálogo: las 346 comunas con su Código Único Territorial (CUT)
-- oficial, que se usa como llave primaria.

