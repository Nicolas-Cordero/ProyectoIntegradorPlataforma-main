ALTER TABLE "universidad" ADD COLUMN "codigo_comuna" INTEGER;

-- 2. Enlace por texto normalizado. Postgres no trae `unaccent` por defecto, así
--    que las tildes se quitan con translate().
UPDATE "universidad" u
SET "codigo_comuna" = c."codigo_comuna"
FROM "comuna" c
WHERE regexp_replace(translate(lower(u."comuna"), 'áéíóúüñ', 'aeiouun'), '[^a-z0-9]', '', 'g')
    = regexp_replace(translate(lower(c."nombre"), 'áéíóúüñ', 'aeiouun'), '[^a-z0-9]', '', 'g');

-- 3. Alias conocidos: nombres de ciudad que no son el nombre de la comuna.
UPDATE "universidad" SET "codigo_comuna" = 12401  -- Natales
WHERE "codigo_comuna" IS NULL AND lower(trim("comuna")) = 'puerto natales';

-- 4. Si queda alguna sin enlazar, se aborta todo (ROLLBACK implícito) y el
--    error lista las filas para corregirlas a mano antes de reintentar.
DO $$
DECLARE
  sin_comuna TEXT;
BEGIN
  SELECT string_agg(format('#%s %s (%s)', "codigo_universidad", "nombre", "comuna"), '; ')
    INTO sin_comuna
    FROM "universidad"
   WHERE "codigo_comuna" IS NULL;
  IF sin_comuna IS NOT NULL THEN
    RAISE EXCEPTION 'Universidades cuya comuna no se encontró en el catálogo: %', sin_comuna;
  END IF;
END $$;

-- 5. Recién ahora, con todo enlazado, se reemplaza la columna de texto.
ALTER TABLE "universidad" ALTER COLUMN "codigo_comuna" SET NOT NULL;
ALTER TABLE "universidad" ADD CONSTRAINT "universidad_codigo_comuna_fkey"
  FOREIGN KEY ("codigo_comuna") REFERENCES "comuna"("codigo_comuna") ON DELETE RESTRICT ON UPDATE CASCADE;

DROP INDEX "universidad_nombre_comuna_key";
CREATE UNIQUE INDEX "universidad_nombre_codigo_comuna_key" ON "universidad"("nombre", "codigo_comuna");
ALTER TABLE "universidad" DROP COLUMN "comuna";

